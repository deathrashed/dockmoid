/* name -> true, for O(1) membership tests. Built once, then reused. */
function nameSet() {
    var list = names()
    var set = {}
    for (var i = 0; i < list.length; i++) {
        if (list[i] !== "") set[list[i]] = true
    }
    return set;
}
