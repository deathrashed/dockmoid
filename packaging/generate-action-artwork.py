#!/usr/bin/env python3
"""Regenerate the shared SVG data map after changing bundled action artwork."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
artwork = {
    p.stem: p.read_text().replace('stroke="#000000"', 'stroke="currentColor"')
    for p in sorted((root / 'contents/assets/lucide').glob('*.svg'))
}
artwork['logo-docker'] = (root / 'contents/assets/logo-docker.svg').read_text().replace('fill="#000000"', 'fill="currentColor"')
for name in ['logo-dockmoid-ring', 'logo-dockmoid-whale']:
    artwork[name] = (root / ('contents/assets/' + name + '.svg')).read_text().replace('#000000', 'currentColor')
(root / 'contents/lib/actionSvg.js').write_text(
    '.pragma library\n// Generated by packaging/generate-action-artwork.py; do not edit by hand.\nvar artwork = '
    + json.dumps(artwork, separators=(',', ':'))
    + ';\nfunction url(name, color) {\n    var svg = artwork[name] || artwork["circle-alert"];\n'
    + '    return "data:image/svg+xml;charset=utf-8," + encodeURIComponent(svg.replace(/currentColor/g, String(color)));\n}\n'
)
print(f'Generated {len(artwork)} shared action SVGs')
