#!/usr/bin/env python3
"""Regenerate the shared SVG data map after changing bundled action artwork.

Only the Lucide icons the code names are embedded: every quoted name in the
QML and JS that resolves (through lib/actionIcons.js) to a bundled Lucide file.
Any other name, such as one a user types for a custom action, is drawn from its
file in contents/assets/lucide instead. `--check` exits 1 when the generated
file is out of date, so the tests catch an icon added without regenerating.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
lucide = root / 'contents/assets/lucide'
target = root / 'contents/lib/actionSvg.js'

# Resolve names exactly as the widget does, by running lib/actionIcons.js.
tokens = set()
for source in sorted((root / 'contents').rglob('*')):
    if source.suffix in ('.qml', '.js') and source != target and 'assets' not in source.parts:
        tokens.update(re.findall(r'["\']([a-z0-9]+(?:-[a-z0-9]+)*)["\']', source.read_text()))
resolver = (root / 'contents/lib/actionIcons.js').read_text().replace('.pragma library', '')
resolved = json.loads(subprocess.run(
    ['node', '-e', resolver + '\nconst names=JSON.parse(require("fs").readFileSync(0,"utf8"));'
     'console.log(JSON.stringify(names.map(n=>path(n).split("/").pop().replace(/\\.svg$/,""))))'],
    input=json.dumps(sorted(tokens)), capture_output=True, text=True, check=True).stdout)
used = {name for name in resolved if (lucide / (name + '.svg')).is_file()}
used.update({'circle-alert', 'external-link'})  # the fallbacks themselves

artwork = {
    name: (lucide / (name + '.svg')).read_text().replace('stroke="#000000"', 'stroke="currentColor"')
    for name in sorted(used)
}
artwork['logo-docker'] = (root / 'contents/assets/logo-docker.svg').read_text().replace('fill="#000000"', 'fill="currentColor"')
for name in ['logo-dockmoid-ring', 'logo-dockmoid-whale']:
    artwork[name] = (root / ('contents/assets/' + name + '.svg')).read_text().replace('#000000', 'currentColor')
output = (
    '.pragma library\n// Generated by packaging/generate-action-artwork.py; do not edit by hand.\nvar artwork = '
    + json.dumps(artwork, separators=(',', ':'))
    + ';\nvar cache = {};\n'
    + '/* Embedded here: drawn with its colour written in. Other names load from their file. */\n'
    + 'function has(name) { return artwork[name] !== undefined }\n'
    + 'function url(name, color) {\n    var key = name + "|" + color;\n    if (cache[key] !== undefined) return cache[key];\n    var svg = artwork[name] || artwork["circle-alert"];\n'
    + '    cache[key] = "data:image/svg+xml;charset=utf-8," + encodeURIComponent(svg.replace(/currentColor/g, String(color)));\n    return cache[key];\n}\n'
)
if '--check' in sys.argv:
    if not target.is_file() or target.read_text() != output:
        sys.exit('contents/lib/actionSvg.js is out of date: run packaging/generate-action-artwork.py')
    sys.exit(0)
target.write_text(output)
print(f'Generated {len(artwork)} shared action SVGs ({target.stat().st_size // 1024} KB)')
